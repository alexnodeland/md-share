#!/usr/bin/env node
// Regenerates src/hljsAliases.ts from highlight.js's own language metadata.
// Run after upgrading highlight.js: `npm run gen:hljs-aliases`.
import { writeFileSync } from 'node:fs';
import hljs from 'highlight.js';

const aliases = {};
for (const name of hljs.listLanguages().sort()) {
  for (const alias of hljs.getLanguage(name).aliases ?? []) aliases[alias.toLowerCase()] = name;
}
const body = Object.entries(aliases)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([alias, name]) => `  ${JSON.stringify(alias)}: ${JSON.stringify(name)},`)
  .join('\n');

writeFileSync(
  new URL('../src/hljsAliases.ts', import.meta.url),
  `// Generated by scripts/gen-hljs-aliases.mjs from highlight.js metadata — do not edit.
// Grammars load lazily by file name, so fence aliases (\`js\`, \`py\`, \`sh\`…)
// must be resolved to that name first.
export const LANGUAGE_ALIASES: Readonly<Record<string, string>> = {
${body}
};

/** The highlight.js grammar file for a fence language, e.g. \`js\` → \`javascript\`. */
export const languageFile = (lang: string): string => {
  const key = lang.toLowerCase();
  return LANGUAGE_ALIASES[key] ?? key;
};
`,
);
